package gcp

import (
	"context"

	"github.com/GoogleCloudPlatform/terraformer/terraformutils"
	"google.golang.org/api/compute/v1"
)

var routerSubresourcesAllowEmptyValues = []string{""}

var routerSubresourcesAdditionalFields = map[string]interface{}{}

type RouterSubresourcesGenerator struct {
	GCPService
}

// InitResources enumerates the routers of the configured region and emits
// the sub-resources embedded in each router resource: NAT configs
// (google_compute_router_nat), BGP peers (google_compute_router_peer) and
// interfaces (google_compute_router_interface). These are not standalone
// API collections, so the compute code generator cannot produce them; the
// provider ID for all three is {project}/{region}/{router}/{name}.
//
// Deliberately not generated:
//   - google_compute_router_nat_address: NAT IP addresses are fields of
//     the NAT config, not separately named API objects.
//   - google_compute_router_route_policy and
//     google_compute_router_named_set: not exposed on the GA compute
//     Router resource.
//   - google_compute_ha_vpn_gateway: the GA compute API has no
//     HA-vs-classic discriminator on VPN gateways; every gateway is
//     already emitted as google_compute_vpn_gateway by the
//     targetVpnGateways generator, so HA gateways are covered and
//     re-emitting them here would double-generate.
//   - google_compute_global_network_endpoint: endpoints are a per-group
//     sub-collection whose members are identified by IP/port rather than
//     by name; the enumerable parent (the global network endpoint group)
//     is generated by globalNetworkEndpointGroups_gen.go.
func (g *RouterSubresourcesGenerator) InitResources() error {
	ctx := context.Background()
	computeService, err := compute.NewService(ctx)
	if err != nil {
		return err
	}
	return g.initResources(ctx, computeService)
}

func (g *RouterSubresourcesGenerator) initResources(ctx context.Context, computeService *compute.Service) error {
	project := g.GetArgs()["project"].(string)
	region := g.GetArgs()["region"].(compute.Region).Name
	return computeService.Routers.List(project, region).Pages(ctx, func(page *compute.RouterList) error {
		for _, router := range page.Items {
			for _, nat := range router.Nats {
				g.Resources = append(g.Resources, g.newRouterSubresource(
					project, region, router.Name, nat.Name, "google_compute_router_nat"))
			}
			for _, peer := range router.BgpPeers {
				g.Resources = append(g.Resources, g.newRouterSubresource(
					project, region, router.Name, peer.Name, "google_compute_router_peer"))
			}
			for _, iface := range router.Interfaces {
				g.Resources = append(g.Resources, g.newRouterSubresource(
					project, region, router.Name, iface.Name, "google_compute_router_interface"))
			}
		}
		return nil
	})
}

func (g *RouterSubresourcesGenerator) newRouterSubresource(project, region, router, name, resourceType string) terraformutils.Resource {
	return terraformutils.NewResource(
		project+"/"+region+"/"+router+"/"+name,
		name,
		resourceType,
		g.ProviderName,
		map[string]string{
			"name":    name,
			"project": project,
			"region":  region,
			"router":  router,
		},
		routerSubresourcesAllowEmptyValues,
		routerSubresourcesAdditionalFields,
	)
}
