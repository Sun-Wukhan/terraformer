func (g *VertexAiGenerator) loadFeaturestoreIam(ctx context.Context, service *aiplatform.Service, featurestoreName string) []terraformutils.Resource {
	resources := []terraformutils.Resource{}
	policy, err := service.Projects.Locations.Featurestores.GetIamPolicy(featurestoreName).Context(ctx).Do()
	if err != nil {
		log.Println(err)
		return resources
	}
	return expandIamPolicy(vertexIamBindings(policy), featurestoreName,
		"google_vertex_ai_featurestore_iam_policy",
		"google_vertex_ai_featurestore_iam_binding",
		"google_vertex_ai_featurestore_iam_member",
		map[string]string{"featurestore": featurestoreName},
		g.vertexResourceFunc())
}

