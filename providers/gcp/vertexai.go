// InitResources enumerates the Vertex AI surface of one project/location:
// datasets, endpoints, indexes and their deployed indexes, metadata stores,
// legacy featurestores (with entity types, features and IAM), feature groups,
// feature online stores (with feature views and IAM), tensorboards (with
// experiments and runs), custom jobs, pipeline jobs, deployment resource
// pools, persistent resources, RAG corpora and files, reasoning engines and
// the per-project cache config singleton.
//
// Deliberately not generated (re-verified in the full-coverage
// sweep against the aiplatform v1 and v1beta1 discovery documents
// and the pinned generated clients):
//   - google_vertex_ai_agent_anomaly_detection_scope,
//     google_vertex_ai_evaluation_metric,
//     google_vertex_ai_model_development_cluster,
//     google_vertex_ai_model_garden_enable_model and
//     google_vertex_ai_online_evaluator: no list or get collection
//     exists for these in aiplatform v1 or v1beta1.
//   - google_vertex_ai_reasoning_engine_iam: reasoning engines
//     expose no getIamPolicy in either the v1 or the v1beta1
//     aiplatform client (endpoints do in v1beta1 — their IAM trio
//     is generated by vertexai_depth.go).
//   - google_vertex_ai_endpoint_with_model_garden_deployment: model-garden
//     deployments are ordinary entries of the same endpoints collection that
//     google_vertex_ai_endpoint already enumerates; they cannot be told
//     apart from the List response, so generating both would double-emit
//     the same API objects.
func (g *VertexAiGenerator) InitResources() error {
	ctx := context.Background()
	region := g.GetArgs()["region"].(compute.Region).Name
	options := []option.ClientOption{}
	if region != "" {
		// Vertex AI resources live behind regional endpoints.
		options = append(options, option.WithEndpoint("https://"+region+"-aiplatform.googleapis.com/v1/"))
	}
	service, err := aiplatform.NewService(ctx, options...)
	if err != nil {
		return err
	}
	if err := g.initResources(ctx, service); err != nil {
		return err
	}
	// Depth pass (vertexai_depth.go): endpoint IAM via the v1beta1
	// client, RAG engine config and semantic governance via raw REST.
	betaOptions := []option.ClientOption{}
	if region != "" {
		betaOptions = append(betaOptions, option.WithEndpoint("https://"+region+"-aiplatform.googleapis.com/v1beta1/"))
	}
	betaService, err := aiplatformbeta.NewService(ctx, betaOptions...)
	if err != nil {
		log.Println(err)
		return nil
	}
	restClient, err := newAuthenticatedHTTPClient(ctx)
	if err != nil {
		log.Println(err)
		return nil
	}
	g.initDepthResources(ctx, betaService, restClient)
	return nil
}

func (g *VertexAiGenerator) initResources(ctx context.Context, service *aiplatform.Service) error {
	project := g.GetArgs()["project"].(string)
	region := g.GetArgs()["region"].(compute.Region).Name
	parent := "projects/" + project + "/locations/" + region

	for _, load := range []func(context.Context, *aiplatform.Service, string) error{
		g.loadDatasets,
		g.loadEndpoints,
		g.loadIndexes,
		g.loadIndexEndpoints,
		g.loadMetadataStores,
		g.loadFeaturestores,
		g.loadFeatureGroups,
		g.loadFeatureOnlineStores,
		g.loadTensorboards,
		g.loadCustomJobs,
		g.loadPipelineJobs,
		g.loadDeploymentResourcePools,
		g.loadPersistentResources,
		g.loadRagCorpora,
		g.loadReasoningEngines,
	} {
		if err := load(ctx, service, parent); err != nil {
			return err
		}
	}
	return g.loadCacheConfig(ctx, service, project)
}

func vertexLabel(name, displayName string) string {
	if displayName != "" {
		return displayName
	}
	parts := strings.Split(name, "/")
	return parts[len(parts)-1]
}

func (g *VertexAiGenerator) baseAttrs() map[string]string {
	return map[string]string{
		"project": g.GetArgs()["project"].(string),
		"region":  g.GetArgs()["region"].(compute.Region).Name,
	}
}

func (g *VertexAiGenerator) newVertexResource(id, name, resourceType string, attrs map[string]string) terraformutils.Resource {
	merged := g.baseAttrs()
	for k, v := range attrs {
		merged[k] = v
	}
	return terraformutils.NewResource(
		id,
		name,
		resourceType,
		g.ProviderName,
		merged,
		vertexAiAllowEmptyValues,
		vertexAiAdditionalFields,
	)
}

// vertexResourceFunc adapts newVertexResource to the
// newResourceFunc shape expandIamPolicy expects.
func (g *VertexAiGenerator) vertexResourceFunc() newResourceFunc {
	return func(id, resourceType string, attrs map[string]string) terraformutils.Resource {
		parts := strings.Split(id, "/")
		return g.newVertexResource(id, parts[len(parts)-1], resourceType, attrs)
	}
}

// vertexIamBindings flattens a live aiplatform IAM policy into the
// package-neutral binding view expandIamPolicy consumes.
func vertexIamBindings(policy *aiplatform.GoogleIamV1Policy) []iamBinding {
	bindings := []iamBinding{}
	if policy == nil {
		return bindings
	}
	for _, binding := range policy.Bindings {
		bindings = append(bindings, iamBinding{Role: binding.Role, Members: binding.Members})
	}
	return bindings
}

