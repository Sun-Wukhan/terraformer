func (g *IamGenerator) addGroupMemberships(svc *iam.Client) error {
	p := iam.NewListGroupsPaginator(svc, &iam.ListGroupsInput{})
	for p.HasMorePages() {
		page, err := p.NextPage(context.TODO())
		if err != nil {
			return err
		}
		for _, group := range page.Groups {
			groupName := StringValue(group.GroupName)
			out, err := svc.GetGroup(context.TODO(), &iam.GetGroupInput{GroupName: group.GroupName})
			if err != nil {
				log.Println(err)
				continue
			}
			if len(out.Users) == 0 {
				continue
			}
			attributes := map[string]string{"users.#": strconv.Itoa(len(out.Users))}
			for i, user := range out.Users {
				attributes["users."+strconv.Itoa(i)] = StringValue(user.UserName)
			}
			g.Resources = append(g.Resources, terraformutils.NewResource(
				groupName,
				groupName,
				"aws_iam_group_membership",
				"aws",
				attributes,
				IamAllowEmptyValues,
				IamAdditionalFields))
		}
	}
	return nil
}

// Per-user depth resources: login profiles, SSH public keys, signing
// certificates and service-specific credentials are all scoped to a
// user, so they are enumerated inside the user list.
func (g *IamGenerator) addPerUserDepthResources(svc *iam.Client) error {
	p := iam.NewListUsersPaginator(svc, &iam.ListUsersInput{})
	for p.HasMorePages() {
		page, err := p.NextPage(context.TODO())
		if err != nil {
			return err
		}
		for _, user := range page.Users {
			userName := StringValue(user.UserName)
			g.addUserLoginProfile(svc, userName)
			g.addUserSSHKeys(svc, userName)
			g.addUserSigningCertificates(svc, userName)
			g.addUserServiceSpecificCredentials(svc, userName)
		}
	}
	return nil
}

func (g *IamGenerator) addUserLoginProfile(svc *iam.Client, userName string) {
	_, err := svc.GetLoginProfile(context.TODO(), &iam.GetLoginProfileInput{UserName: &userName})
	if err != nil {
		return // no login profile for this user
	}
	g.Resources = append(g.Resources, terraformutils.NewSimpleResource(
		userName,
		userName,
		"aws_iam_user_login_profile",
		"aws",
		IamAllowEmptyValues))
}

func (g *IamGenerator) addUserSSHKeys(svc *iam.Client, userName string) {
	p := iam.NewListSSHPublicKeysPaginator(svc, &iam.ListSSHPublicKeysInput{UserName: &userName})
	for p.HasMorePages() {
		page, err := p.NextPage(context.TODO())
		if err != nil {
			log.Println(err)
			return
		}
		for _, key := range page.SSHPublicKeys {
			keyID := StringValue(key.SSHPublicKeyId)
			g.Resources = append(g.Resources, terraformutils.NewSimpleResource(
				userName+":"+keyID+":SSH",
				userName+"_"+keyID,
				"aws_iam_user_ssh_key",
				"aws",
				IamAllowEmptyValues))
		}
	}
}

