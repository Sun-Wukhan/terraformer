func (g *IamGenerator) addUserServiceSpecificCredentials(svc *iam.Client, userName string) {
	input := &iam.ListServiceSpecificCredentialsInput{UserName: &userName}
	for {
		page, err := svc.ListServiceSpecificCredentials(context.TODO(), input)
		if err != nil {
			log.Println(err)
			return
		}
		for _, cred := range page.ServiceSpecificCredentials {
			id := StringValue(cred.ServiceName) + ":" + userName + ":" + StringValue(cred.ServiceSpecificCredentialId)
			g.Resources = append(g.Resources, terraformutils.NewSimpleResource(
				id,
				userName+"_"+StringValue(cred.ServiceSpecificCredentialId),
				"aws_iam_service_specific_credential",
				"aws",
				IamAllowEmptyValues))
		}
		if !page.IsTruncated {
			return
		}
		input.Marker = page.Marker
	}
}
