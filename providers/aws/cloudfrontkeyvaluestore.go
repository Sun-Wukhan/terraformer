package aws

import (
	"context"

	"github.com/GoogleCloudPlatform/terraformer/terraformutils"
	"github.com/aws/aws-sdk-go-v2/aws"
	"github.com/aws/aws-sdk-go-v2/service/cloudfront"
	"github.com/aws/aws-sdk-go-v2/service/cloudfrontkeyvaluestore"
)

var cloudFrontKeyValueStoreAllowEmptyValues = []string{"tags."}

type CloudFrontKeyValueStoreGenerator struct {
	AWSService
}

// InitResources enumerates the keys of every CloudFront key value
// store (the stores themselves are generated by the cloudfront
// family). Provider ID format: kvs_arn,key.
//
// aws_cloudfrontkeyvaluestore_keys_exclusive is intentionally not
// generated: it is an exclusive-management resource whose state is
// the full key set of one store, with no independent API object; its
// content is exactly the aws_cloudfrontkeyvaluestore_key set
// generated here, and the two would fight over the same keys.
func (g *CloudFrontKeyValueStoreGenerator) InitResources() error {
	config, e := g.generateConfig()
	if e != nil {
		return e
	}
	cfClient := cloudfront.NewFromConfig(config)
	kvsClient := cloudfrontkeyvaluestore.NewFromConfig(config)
	var marker *string
	for {
		out, err := cfClient.ListKeyValueStores(context.TODO(), &cloudfront.ListKeyValueStoresInput{Marker: marker})
		if err != nil {
			return err
		}
		for _, store := range out.KeyValueStoreList.Items {
			if err := g.addKeys(kvsClient, StringValue(store.ARN)); err != nil {
				return err
			}
		}
		marker = out.KeyValueStoreList.NextMarker
		if marker == nil {
			return nil
		}
	}
}

func (g *CloudFrontKeyValueStoreGenerator) addKeys(client *cloudfrontkeyvaluestore.Client, kvsArn string) error {
	input := &cloudfrontkeyvaluestore.ListKeysInput{KvsARN: aws.String(kvsArn)}
	for {
		out, err := client.ListKeys(context.TODO(), input)
		if err != nil {
			return err
		}
		for _, item := range out.Items {
			g.Resources = append(g.Resources, terraformutils.NewResource(
				kvsArn+","+StringValue(item.Key),
				StringValue(item.Key),
				"aws_cloudfrontkeyvaluestore_key",
				"aws",
				map[string]string{"key_value_store_arn": kvsArn},
				cloudFrontKeyValueStoreAllowEmptyValues,
				map[string]interface{}{},
			))
		}
		if out.NextToken == nil {
			return nil
		}
		input.NextToken = out.NextToken
	}
}
