package aws

import (
	"context"
	"log"

	"github.com/GoogleCloudPlatform/terraformer/terraformutils"
	"github.com/aws/aws-sdk-go-v2/aws"
	"github.com/aws/aws-sdk-go-v2/service/secretsmanager"
)

// Secrets Manager depth pass (AWS full-coverage sweep, security
// cluster). Per secret enumerated by ListSecrets:
//
//   - aws_secretsmanager_secret_policy (provider ID = secret ARN),
//     only when GetResourcePolicy returns a policy.
//   - aws_secretsmanager_secret_rotation (provider ID = secret ARN),
//     only when DescribeSecret reports rotation enabled.
//   - aws_secretsmanager_secret_version (provider ID =
//     secret_id|version_id, verified against the provider docs),
//     for every version from ListSecretVersionIds.
//
// Intentionally not generated: aws_secretsmanager_tag is per-tag
// glue — tags are attributes of the aws_secretsmanager_secret
// resource already generated by secretsmanager.go, so emitting one
// resource per tag key would double-manage them.
func (g *SecretsManagerGenerator) addDepthResources(svc *secretsmanager.Client) {
	p := secretsmanager.NewListSecretsPaginator(svc, &secretsmanager.ListSecretsInput{})
	for p.HasMorePages() {
		page, err := p.NextPage(context.TODO())
		if err != nil {
			log.Println(err)
			return
		}
		for _, secret := range page.SecretList {
			arn := StringValue(secret.ARN)
			name := StringValue(secret.Name)
			g.addSecretPolicy(svc, arn, name)
			g.addSecretRotation(svc, arn, name)
			g.addSecretVersions(svc, arn, name)
		}
	}
}

func (g *SecretsManagerGenerator) addSecretPolicy(svc *secretsmanager.Client, arn, name string) {
	out, err := svc.GetResourcePolicy(context.TODO(), &secretsmanager.GetResourcePolicyInput{SecretId: &arn})
	if err != nil || out.ResourcePolicy == nil || *out.ResourcePolicy == "" {
		return
	}
	g.Resources = append(g.Resources, terraformutils.NewSimpleResource(
		arn,
		name,
		"aws_secretsmanager_secret_policy",
		"aws",
		secretsmanagerAllowEmptyValues))
}

func (g *SecretsManagerGenerator) addSecretRotation(svc *secretsmanager.Client, arn, name string) {
	out, err := svc.DescribeSecret(context.TODO(), &secretsmanager.DescribeSecretInput{SecretId: &arn})
	if err != nil || !aws.ToBool(out.RotationEnabled) {
		return
	}
	g.Resources = append(g.Resources, terraformutils.NewSimpleResource(
		arn,
		name,
		"aws_secretsmanager_secret_rotation",
		"aws",
		secretsmanagerAllowEmptyValues))
}

func (g *SecretsManagerGenerator) addSecretVersions(svc *secretsmanager.Client, arn, name string) {
	p := secretsmanager.NewListSecretVersionIdsPaginator(svc, &secretsmanager.ListSecretVersionIdsInput{
		SecretId:          &arn,
		IncludeDeprecated: aws.Bool(true),
	})
	for p.HasMorePages() {
		page, err := p.NextPage(context.TODO())
		if err != nil {
			log.Println(err)
			return
		}
		for _, version := range page.Versions {
			versionID := StringValue(version.VersionId)
			g.Resources = append(g.Resources, terraformutils.NewSimpleResource(
				arn+"|"+versionID,
				name+"_"+versionID,
				"aws_secretsmanager_secret_version",
				"aws",
				secretsmanagerAllowEmptyValues))
		}
	}
}
